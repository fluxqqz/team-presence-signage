-- =========================================================
-- PRESENCE STATUS ENUM
-- =========================================================

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'presence_status'
      AND n.nspname = 'public'
  ) THEN
    CREATE TYPE public.presence_status AS ENUM (
      'hadir',
      'sakit',
      'izin_terlambat',
      'cuti',
      'lapangan',
      'wfh',
      'off'
    );
  ELSE
    ALTER TYPE public.presence_status ADD VALUE IF NOT EXISTS 'off';
  END IF;
END
$$;


